-- C/C++ support: clangd + clang-tidy, but ONLY inside the devcontainer.
--
-- The outer (host) nvim is an orchestration shell: it has no clangd and no
-- compile database, so attaching clangd there only produces noise. We attach
-- clangd only when running inside the container, which ships
-- /opt/clangd_<ver>/bin/clangd and whose CMake build writes the compile DB to
-- server/cmake-build/.clangd (mirrors .vscode/settings.json).
local in_container = vim.fn.filereadable("/.dockerenv") == 1

local function clangd_binary()
  local found = vim.fn.glob("/opt/clangd_*/bin/clangd", false, true)
  if type(found) == "table" and #found > 0 then
    return found[1]
  end
  return "clangd"
end

-- Walk up from the launch dir looking for the compile DB generated by
-- server/CMakeLists.txt (kept in sync with .vscode's --compile-commands-dir).
local function find_compile_commands_dir()
  local dir = vim.fn.getcwd()
  while dir ~= "/" and dir ~= "" do
    for _, sub in ipairs({ "/server/cmake-build/.clangd", "/server/cmake-build/debug" }) do
      if vim.fn.filereadable(dir .. sub .. "/compile_commands.json") == 1 then
        return dir .. sub
      end
    end
    local parent = vim.fn.fnamemodify(dir, ":h")
    if parent == dir then
      break
    end
    dir = parent
  end
  return nil
end

local servers = {}
if in_container then
  local cmd = {
    clangd_binary(),
    "--background-index",
    "--clang-tidy",
    "--header-insertion=iwyu",
    "--completion-style=detailed",
    "--function-arg-placeholders",
    "--fallback-style=llvm",
  }
  local compile_commands_dir = find_compile_commands_dir()
  if compile_commands_dir then
    table.insert(cmd, "--compile-commands-dir=" .. compile_commands_dir)
  end

  servers.clangd = {
    cmd = cmd,
    root_markers = { "compile_commands.json", "compile_flags.txt", "CMakeLists.txt", ".clangd", ".git" },
    capabilities = { offsetEncoding = { "utf-16" } },
    init_options = {
      usePlaceholders = true,
      completeUnimported = true,
      clangdFileStatus = true,
    },
  }
end

return {
  -- Treesitter C/C++ parsing (syntax only; harmless in the host window too).
  {
    "nvim-treesitter/nvim-treesitter",
    opts = { ensure_installed = { "cpp" } },
  },

  {
    "neovim/nvim-lspconfig",
    opts = { servers = servers },
  },
}
